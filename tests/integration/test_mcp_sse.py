from __future__ import annotations

import asyncio
import socket

import pytest
from fastmcp import Client

from querymesh.agents.researcher import ResearcherAgent
from querymesh.mcp.servers.research_server import build_research_server
from querymesh.llm import get_llm


def get_free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


async def wait_for_server(host: str, port: int, timeout: float = 10.0, ) -> None:
    deadline = asyncio.get_running_loop().time() + timeout

    while asyncio.get_running_loop().time() < deadline:
        try:
            _, writer = await asyncio.open_connection(host, port)
            writer.close()
            await writer.wait_closed()
            return
        except OSError:
            await asyncio.sleep(0.05)

    raise TimeoutError(f"MCP server did not start on {host}:{port}")


@pytest.mark.asyncio
@pytest.mark.real_llm
async def test_research_mcp_sse_with_real_researcher():
    # Use your configured real LLM.
    llm = get_llm()

    researcher = ResearcherAgent(llm=llm)

    # Build the actual MCP server with the real agent.
    server = build_research_server(researcher)

    host = "127.0.0.1"
    port = get_free_port()

    server_task = asyncio.create_task(
        server.run_async(transport="sse", host=host, port=port,)
    )

    try:
        await wait_for_server(host, port)

        # Real network/SSE connection.
        async with Client(f"http://{host}:{port}/sse") as client:

            tools = await client.list_tools()

            tool_names = {tool.name for tool in tools}

            assert "search_papers" in tool_names

            # This now reaches the REAL ResearcherAgent.
            result = await client.call_tool(
                "search_papers",
                {
                    "query": "How does self-attention work in transformers?"
                },
            )

            assert result is not None

            print("\nREAL RESEARCHER RESULT:")
            print(result)

    finally:
        server_task.cancel()

        try:
            await server_task
        except asyncio.CancelledError:
            pass
